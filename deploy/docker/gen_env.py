#!/usr/bin/env python3
"""Write a .env with random credentials for the local compose stack.

Never overwrites existing values; if the file already exists, only keys it lacks are appended.
"""

from __future__ import annotations

import base64
import os
import secrets
import sys
from pathlib import Path


def generate() -> dict[str, str]:
    kms_key = base64.b64encode(secrets.token_bytes(32)).decode()
    values = {
        "MINIO_ROOT_USER": "u" + secrets.token_hex(8),
        "MINIO_ROOT_PASSWORD": secrets.token_hex(24),
        "MINIO_KMS_SECRET_KEY": f"bridgeloan-key:{kms_key}",
        "POSTGRES_PASSWORD": secrets.token_hex(24),
        "LAKEKEEPER_PG_ENCRYPTION_KEY": secrets.token_hex(32),
        "GATEWAY_SECRET": secrets.token_hex(32),
        # HS256 signing key for the gateway's static per-key-id JWT (ADR-0005)
        "JWT_SIGNING_KEY": secrets.token_hex(32),
    }
    return values


def render() -> str:
    header = (
        "# Generated by `make env`; random local-only credentials. Gitignored; do not commit.\n"
    )
    return header + "".join(f"{k}={v}\n" for k, v in generate().items())


def main(argv: list[str]) -> int:
    target = Path(argv[1] if len(argv) > 1 else ".env")
    if target.exists():
        present = {
            line.split("=", 1)[0].strip()
            for line in target.read_text().splitlines()
            if "=" in line and not line.lstrip().startswith("#")
        }
        missing = {k: v for k, v in generate().items() if k not in present}
        if not missing:
            print(f"{target} exists; leaving it unchanged")
            return 0
        text = target.read_text()
        with open(target, "a") as fh:
            if text and not text.endswith("\n"):
                fh.write("\n")
            fh.write("".join(f"{k}={v}\n" for k, v in missing.items()))
        print(f"{target} exists; added missing keys: {', '.join(missing)}")
        return 0
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(render())
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
