#!/usr/bin/env python3
"""Iceberg snapshot expiry and compaction for a table in the Lakekeeper catalog.

Usage:
    expire_snapshots.py --table ns.table [--retain-last 1] [--compact]
        [--uri http://127.0.0.1:8181/catalog] [--warehouse bridgeloan]
        [--s3-endpoint http://127.0.0.1:9000]

S3 credentials are read from MINIO_ROOT_USER / MINIO_ROOT_PASSWORD (generated by `make env`).

Compaction (``--compact``) rewrites all live rows into fresh data files through a single
overwrite, because pyiceberg has no native rewrite_data_files; it runs before expiry so the
pre-compaction snapshots (and the many small files they reference) can then be dropped.
Expiry drops snapshot metadata only; physical orphan-file removal is left to bucket lifecycle.
"""

from __future__ import annotations

import argparse
import os
import sys

from pyiceberg.catalog import Catalog, load_catalog
from pyiceberg.io import load_file_io
from pyiceberg.table import Table


def expire_snapshots(table: Table, retain_last: int = 1) -> list[int]:
    """Expire all but the newest ``retain_last`` snapshots; return the expired ids."""
    if retain_last < 1:
        raise ValueError("retain_last must be >= 1")
    snapshots = sorted(table.snapshots(), key=lambda s: s.timestamp_ms)
    current = table.current_snapshot()
    keep = {s.snapshot_id for s in snapshots[-retain_last:]}
    if current is not None:
        keep.add(current.snapshot_id)
    expired = [s.snapshot_id for s in snapshots if s.snapshot_id not in keep]
    if expired:
        table.maintenance.expire_snapshots().by_ids(expired).commit()
    return expired


def compact(table: Table) -> None:
    """Rewrite the table's live rows into compacted data files (one new snapshot)."""
    data = table.scan().to_arrow()
    table.overwrite(data)


def with_endpoint(table: Table, endpoint: str) -> Table:
    """Client-side ``s3.endpoint`` override.

    Lakekeeper returns the warehouse's internal endpoint (``http://minio:9000``) in the table
    config, and pyiceberg lets server config win over client config. On the host that name
    does not resolve, so rebuild the table's FileIO with the endpoint we can actually reach.
    """
    props = {**table.io.properties, "s3.endpoint": endpoint, "s3.path-style-access": "true"}
    table.io = load_file_io(props, table.metadata_location)
    return table


def load_catalog_from_args(args: argparse.Namespace) -> Catalog:
    return load_catalog(
        "lakekeeper",
        **{
            "type": "rest",
            "uri": args.uri,
            "warehouse": args.warehouse,
            "s3.endpoint": args.s3_endpoint,
            "s3.path-style-access": "true",
            "s3.access-key-id": os.environ.get("MINIO_ROOT_USER", ""),
            "s3.secret-access-key": os.environ.get("MINIO_ROOT_PASSWORD", ""),
            "s3.region": "us-east-1",
        },
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--table", required=True, help="namespace.table")
    parser.add_argument("--retain-last", type=int, default=1)
    parser.add_argument("--compact", action="store_true")
    parser.add_argument("--uri", default="http://127.0.0.1:8181/catalog")
    parser.add_argument("--warehouse", default="bridgeloan")
    parser.add_argument("--s3-endpoint", default="http://127.0.0.1:9000")
    args = parser.parse_args(argv)

    catalog = load_catalog_from_args(args)
    table = with_endpoint(catalog.load_table(args.table), args.s3_endpoint)
    if args.compact:
        compact(table)
        table = with_endpoint(catalog.load_table(args.table), args.s3_endpoint)
    expired = expire_snapshots(table, retain_last=args.retain_last)
    print(f"{args.table}: expired {len(expired)} snapshot(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
